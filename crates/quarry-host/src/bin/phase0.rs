//! Phase-0 measurements (06-roadmap.md): wasmi interpretation penalty,
//! plugin.transition() snapshot cost, and memory behaviour, measured against
//! the shipped artifact. Results land in docs/phase0-findings.md.
//!
//! Usage: cargo run --release -p quarry-host --bin phase0 [--big MB]

use ciborium::Value;
use quarry_host::Plugin;
use std::path::PathBuf;
use std::process::Command;
use std::time::Instant;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf()
}

fn encode(v: &Value) -> Vec<u8> {
    let mut out = Vec::new();
    ciborium::into_writer(v, &mut out).unwrap();
    out
}

fn meta(seed: i64) -> Vec<u8> {
    encode(&Value::Map(vec![
        (
            Value::Text("now".into()),
            Value::from(1_768_867_200_000_000i64),
        ),
        (Value::Text("seed".into()), Value::from(seed)),
    ]))
}

fn request(sql: &str) -> Vec<u8> {
    encode(&Value::Map(vec![(
        Value::Text("sql".into()),
        Value::Text(sql.into()),
    )]))
}

fn time<F: FnMut()>(iters: u32, mut f: F) -> f64 {
    let start = Instant::now();
    for _ in 0..iters {
        f();
    }
    start.elapsed().as_secs_f64() / iters as f64
}

fn main() {
    let big_mb: usize = std::env::args()
        .skip_while(|a| a != "--big")
        .nth(1)
        .and_then(|v| v.parse().ok())
        .unwrap_or(8);

    let fixtures = repo_root().join("tests/fixtures/generated");
    if !fixtures.join("basic.sqlite").exists() {
        Command::new("python3")
            .arg(repo_root().join("tools/gen_fixtures.py"))
            .status()
            .unwrap();
    }
    let big_path = fixtures.join("big.sqlite");
    if !big_path.exists() {
        eprintln!("building {big_mb} MB big.sqlite…");
        Command::new("python3")
            .arg(repo_root().join("tools/gen_fixtures.py"))
            .args(["--big", &big_mb.to_string()])
            .status()
            .unwrap();
    }
    let basic = std::fs::read(fixtures.join("basic.sqlite")).unwrap();
    let big = std::fs::read(&big_path).unwrap();

    println!("# Phase-0 measurements (machine-generated by quarry-host/bin/phase0)\n");
    println!(
        "- artifact: build/quarry-sqlite.wasm ({} bytes)",
        std::fs::metadata(repo_root().join("build/quarry-sqlite.wasm"))
            .map(|m| m.len())
            .unwrap_or(0)
    );
    println!(
        "- basic.sqlite: {} bytes; big.sqlite: {} bytes\n",
        basic.len(),
        big.len()
    );

    let plugin = Plugin::load_shipped().expect("build_wasm.sh first");

    // Q4: transition cost (open + snapshot) by database size.
    for (name, db) in [("basic", &basic), ("big", &big)] {
        let t = time(if db.len() > 4_000_000 { 1 } else { 10 }, || {
            let _ = plugin.transition("open_1", &[&meta(0), db]).unwrap();
        });
        let handle = plugin.transition("open_1", &[&meta(0), db]).unwrap();
        println!(
            "- transition(open) {name}: {:.1} ms; snapshot {} bytes ({:.2}x db)",
            t * 1e3,
            handle.snapshot_bytes().unwrap(),
            handle.snapshot_bytes().unwrap() as f64 / db.len() as f64
        );
    }

    // Q2: wasmi interpretation penalty on representative queries.
    // NOTE: the native engine allows one live connection per process (global
    // clock/RNG state), so native measurements are scoped per database —
    // never hold two native connections at once.
    let wasm_db = plugin.transition("open_1", &[&meta(0), &basic]).unwrap();
    let big_wasm = plugin.transition("open_1", &[&meta(0), &big]).unwrap();
    let basic_cases: &[(&str, &str)] = &[
        ("small aggregate", "SELECT region, sum(amount), avg(price) FROM orders GROUP BY region"),
        ("200-row scan", "SELECT * FROM orders"),
        ("sort 200 rows", "SELECT * FROM orders ORDER BY note"),
        ("recursive cte 2k", "WITH RECURSIVE c(n) AS (SELECT 1 UNION ALL SELECT n+1 FROM c WHERE n<2000) SELECT sum(n) FROM c"),
    ];
    let big_cases: &[(&str, &str)] = &[
        ("big count", "SELECT count(*) FROM events"),
        (
            "big group-by",
            "SELECT kind, count(*), max(ts) FROM events GROUP BY kind",
        ),
        ("big point lookup", "SELECT * FROM events WHERE id = 12345"),
    ];
    println!("\n| query | native | wasmi | penalty |\n|---|---|---|---|");
    let bench = |cases: &[(&str, &str)], wdb: &Plugin, db_bytes: &[u8], iters: u32| {
        let native = quarry_engine::Connection::open(&meta(0), &[db_bytes]).unwrap();
        for (name, sql) in cases {
            let req = request(sql);
            let tw = time(iters, || {
                wdb.call("query", &[&req]).unwrap();
            });
            let tn = time(iters, || {
                native.query(&req);
            });
            println!(
                "| {name} | {:.2} ms | {:.2} ms | {:.1}x |",
                tn * 1e3,
                tw * 1e3,
                tw / tn
            );
        }
    };
    bench(basic_cases, &wasm_db, &basic, 3);
    bench(big_cases, &big_wasm, &big, 1);

    // Q1 evidence: no wasmi memory limit — grow far beyond defaults.
    let env = wasm_db
        .call(
            "query",
            &[&request(
                "SELECT count(*) FROM (SELECT randomblob(1000000) AS b FROM orders LIMIT 64)",
            )],
        )
        .unwrap();
    println!(
        "\n- 64 MB of transient blobs allocated inside the plugin without any host limit ({} byte envelope) — wasmi imposes no memory ceiling (C-2)",
        env.len()
    );
}
